// Generates src/core/gen1/moves.ts (type, power, accuracy, PP for each move) from the pokered disassembly,
// and cross-checks the move order against MOVE_NAMES. Run only when you want to regenerate the table:
//
//   git clone --depth 1 https://github.com/pret/pokered /tmp/pokered
//   node scripts/gen-moves.mjs /tmp/pokered
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MOVE_NAMES } from '../src/core/gen1/data.ts';

const src = process.argv[2] && resolve(process.argv[2]);
if (!src) { console.error('Usage: node scripts/gen-moves.mjs <path to a pokered checkout>'); process.exit(1); }

const asm = await readFile(join(src, 'data', 'moves', 'moves.asm'), 'utf8');
const rows = [...asm.matchAll(/^\s*move\s+(\w+),\s*(\w+),\s*(\d+),\s*(\w+),\s*(\d+),\s*(\d+)\s*$/gm)];
const TYPE = (t) => {
  const name = t.replace(/_TYPE$/, '');
  return name[0] + name.slice(1).toLowerCase();
};
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');

const lines = [];
const problems = [];
rows.forEach((m, i) => {
  const id = i + 1;
  const [, constName, , power, type, acc, pp] = m;
  const cleanName = constName === 'PSYCHIC_M' ? 'PSYCHIC' : constName; // the disassembly avoids a clash with the type
  if (norm(cleanName) !== norm(MOVE_NAMES[id] ?? '')) problems.push(`#${id}: pokered ${constName} vs app "${MOVE_NAMES[id]}"`);
  lines.push(`  ['${TYPE(type)}', ${power}, ${acc}, ${pp}], // ${id} ${MOVE_NAMES[id] ?? constName}`);
});
if (rows.length !== MOVE_NAMES.length - 1) problems.push(`pokered has ${rows.length} moves, app has ${MOVE_NAMES.length - 1}`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const out = `// Per-move data for Gen 1: [type, power, accuracy %, base PP], indexed by move id (1-165).
// Generated by scripts/gen-moves.mjs from the pret/pokered disassembly (data/moves/moves.asm). Do not edit by hand.

export interface MoveInfo { type: string; power: number; accuracy: number; pp: number }

const TABLE: [type: string, power: number, accuracy: number, pp: number][] = [
${lines.join('\n')}
];

/** Info for a move id, or null for "no move" (0) and ids that don't exist. */
export function moveInfo(id: number): MoveInfo | null {
  const row = TABLE[id - 1];
  return row ? { type: row[0], power: row[1], accuracy: row[2], pp: row[3] } : null;
}

/**
 * The most PP a move can have after \`ppUps\` PP Ups. Each PP Up adds a fifth of the base PP, at most 7,
 * so 40-PP moves top out at 61 (the game stores PP in 6 bits, so 63 is the hard ceiling).
 */
export function maxPp(id: number, ppUps: number): number {
  const info = moveInfo(id);
  if (!info) return 0;
  const bonus = Math.min(7, Math.floor(info.pp / 5));
  return (info.pp + bonus * Math.max(0, Math.min(3, ppUps))) & 63;
}
`;
await writeFile(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'core', 'gen1', 'moves.ts'), out);
console.log(`Wrote ${rows.length} moves to src/core/gen1/moves.ts`);

// Also report the TM/HM list so the TM disc colours in itemSprites.ts can be checked against it.
const items = await readFile(join(src, 'constants', 'item_constants.asm'), 'utf8');
const tms = [...items.matchAll(/add_tm\s+(\w+)/g)].map((m) => m[1]);
const hms = [...items.matchAll(/add_hm\s+(\w+)/g)].map((m) => m[1]);
const typeOf = new Map(rows.map((m) => [norm(m[1]), TYPE(m[4])]));
console.log('TM types:', tms.map((n) => typeOf.get(norm(n))?.toLowerCase()).join(','));
console.log('HM moves:', hms.join(','));
