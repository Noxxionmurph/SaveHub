// Pokémon box icons are drawn with their feet on a common baseline, so the art sits low in its canvas. This
// measures where each icon's visible pixels really are and writes src/ui/spriteOffsets.ts, which the UI uses to
// nudge every icon so it looks centred. Run after importing sprites (import-sprites.mjs does this for you).
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { centreOffset } from './lib/png-alpha.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rows = [];
let size = null;
for (let dex = 1; dex <= 386; dex++) {
  const o = centreOffset(await readFile(join(root, 'assets', 'sprites', 'pokemon', `${dex}.png`)));
  size ??= [o.width, o.height];
  if (o.width !== size[0] || o.height !== size[1]) throw new Error(`icon ${dex} is ${o.width}x${o.height}, expected ${size.join('x')}`);
  rows.push([o.dx, o.dy]);
}
const body = rows.map(([dx, dy], i) => `  [${dx}, ${dy}], // ${i + 1}`).join('\n');
await writeFile(join(root, 'src', 'ui', 'spriteOffsets.ts'), `// Generated by scripts/measure-icons.mjs from assets/sprites/pokemon/*.png. Do not edit by hand.
// For each Pokémon icon (index = National Dex number, entry 0 unused): how many pixels the visible art's centre
// sits right of / below the middle of the ${size[0]}x${size[1]} canvas. The UI shifts the image back by that much.

export const ICON_SIZE = [${size[0]}, ${size[1]}] as const;

export const ICON_OFFSETS: readonly (readonly [dx: number, dy: number])[] = [
  [0, 0],
${body}
];
`);
console.log(`Wrote src/ui/spriteOffsets.ts for ${rows.length} icons (${size.join('x')}).`);
