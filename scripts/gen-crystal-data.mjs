// Generates src/core/gen2/crystalTables.ts (what Pokémon Crystal adds to the Gold / Silver tables: its four new key
// items and the place names it records where a Pokémon was caught) from the pret/pokecrystal disassembly. Run only
// when you want to regenerate it:
//
//   git clone --depth 1 https://github.com/pret/pokecrystal /tmp/pokecrystal
//   node scripts/gen-crystal-data.mjs /tmp/pokecrystal
//
// Crystal's species, base stats and moves are the same as Gold's (only some level-up moves changed, which the editor
// doesn't use), so those stay in tables.ts.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ITEM_TABLE } from '../src/core/gen2/tables.ts';

const src = process.argv[2] && resolve(process.argv[2]);
if (!src) { console.error('Usage: node scripts/gen-crystal-data.mjs <path to a pokecrystal checkout>'); process.exit(1); }
const read = (p) => readFile(join(src, p), 'utf8');
const problems = [];

const SMALL = new Set(['OF']);
const title = (s) => s.replace(/<BSP>/g, ' ').replace(/\.(?=\S)/g, '. ').split(' ')
  .map((w, i) => (i > 0 && SMALL.has(w) ? w.toLowerCase() : w.split('-').map((p) => (p ? p[0] + p.slice(1).toLowerCase() : p)).join('-')))
  .join(' ');

// ---- items: names Crystal gives to ids Gold and Silver leave unused ----
const itemNames = [...(await read('data/items/names.asm')).matchAll(/li "([^"]*)"/g)].map((m) => m[1]);
const itemConsts = [...(await read('constants/item_constants.asm')).matchAll(/^\s*(?:const|add_tm|add_hm)\s+(\w+)/gm)].map((m) => m[1]).filter((c) => c !== 'TM_' && c !== 'HM_').slice(1);
const attrs = [...(await read('data/items/attributes.asm')).matchAll(/^\s*item_attribute\s+[^,]+,\s*(\w+),\s*[^,]+,\s*([^,]+?),\s*(\w+),/gm)];
const ITEM_FIX = { 'GS BALL': 'GS Ball' };
const POCKET = { ITEM: 'item', KEY_ITEM: 'key', BALL: 'ball', TM_HM: 'tmhm' };
const items = [];
for (const [id, gsName] of ITEM_TABLE) {
  const konst = itemConsts[id - 1];
  // TERU-SAMA is the name the game gives its dummy entries (Town Map and Poké Flute are leftovers from Gen 1).
  if (gsName || !konst || /^ITEM_[0-9A-F]{2}$/.test(konst) || itemNames[id - 1] === 'TERU-SAMA') continue;
  const pocket = POCKET[attrs[id - 1]?.[3]];
  if (!pocket) { problems.push(`item 0x${id.toString(16)} ${konst}: no pocket`); continue; }
  items.push(`  [0x${id.toString(16).padStart(2, '0')}, ${JSON.stringify(ITEM_FIX[itemNames[id - 1]] ?? title(itemNames[id - 1]))}, '${pocket}'], // ${konst}`);
}
if (items.length !== 4) problems.push(`expected 4 Crystal-only items, found ${items.length}`);

// ---- landmarks, in constants/landmark_constants.asm order ----
const landmarkAsm = await read('data/maps/landmarks.asm');
const labels = [...landmarkAsm.matchAll(/^\s*landmark\s+-?\d+,\s*-?\d+,\s*(\w+)/gm)].map((m) => m[1]);
const strings = Object.fromEntries([...landmarkAsm.matchAll(/^(\w+):\s*db "([^"]*)@"/gm)].map((m) => [m[1], m[2]]));
const landmarks = labels.map((l) => {
  if (!(l in strings)) problems.push(`landmark ${l}: no name`);
  return l === 'SpecialMapName' ? '' : title(strings[l] ?? '');
});
const NUM_LANDMARKS = 0x60;
if (landmarks.length !== NUM_LANDMARKS) problems.push(`expected ${NUM_LANDMARKS} landmarks, found ${landmarks.length}`);

if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const out = `// Generated by scripts/gen-crystal-data.mjs from pret/pokecrystal. Do not edit by hand.

/** Items only Crystal has: id, name and pocket. In Gold and Silver these ids are unused placeholders. */
export const CRYSTAL_ITEMS: readonly [id: number, name: string, pocket: 'item' | 'key' | 'ball' | 'tmhm'][] = [
${items.join('\n')}
];

/**
 * The place names Crystal records where a Pokémon was caught (data/maps/landmarks.asm), by landmark id. Id 0 is the
 * game's "special" entry (no place recorded); 0x7E means a gift and 0x7F an event.
 */
export const LANDMARK_NAMES: readonly string[] = ${JSON.stringify(landmarks)};
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '../src/core/gen2/crystalTables.ts');
await writeFile(dest, out);
console.log(`wrote ${dest}: ${items.length} items, ${landmarks.length} landmarks`);
